/* 通用词库数量兜底：每个时段固定 50 条问候 + 50 条短句，避免手改时漏条。 */
(function normalizeHomeText() {
  const periods = ['night', 'morning', 'forenoon', 'noon', 'afternoon', 'evening'];
  const pads = {
    zh: {
      greetings: ['早安，今天也要好好吃饭 🍞', '慢一点，今天也会很好 🌿', '记得给自己留一点空白 ☁️'],
      quotes: ['—— 今天也请好好照顾自己。', '—— 慢慢来，日子会给你答案。', '—— 面包会有的，好心情也会有的。']
    },
    en: {
      greetings: ['Good day — remember to eat well 🍞', 'Go slowly; today will be kind 🌿', 'Leave yourself a little space ☁️'],
      quotes: ['—— Take good care of yourself today.', '—— Go slowly; the day will answer in time.', '—— There will be bread, and a good mood too.']
    }
  };
  ['zh', 'en'].forEach((lang) => {
    ['greetings', 'quotes'].forEach((type) => {
      const want = 50;
      periods.forEach((period) => {
        const arr = window.BB_HOME_TEXT[lang][type][period];
        if (!Array.isArray(arr)) return;
        while (arr.length < want) {
          const pad = pads[lang][type][arr.length % pads[lang][type].length];
          arr.push(pad);
        }
        if (arr.length > want) arr.length = want;
      });
    });
  });
})();
