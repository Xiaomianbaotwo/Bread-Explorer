夏荷

夏之西湖，荷为主。曲院风荷，水面开阔，荷塘连片，叶如盖，花如灯。清晨露在叶心，圆而欲滚，风来叶倾，露碎成珠，复聚成光。荷叶层层叠叠，碧绿中含着水汽，边缘微卷，脉络分明。荷花自叶间挺出，有初开者，瓣尖微启，色如浅霞；有半开者，花心犹藏，影落水面；有盛放者，舒展无碍，白者净，粉者柔，红者艳。风过荷塘，万叶同响，如细雨骤至；风止，花影静立，湖面复平。荷香不浓不烈，随水汽浮，随晨光散，随暮色沉，清而不腻，远而愈真。

