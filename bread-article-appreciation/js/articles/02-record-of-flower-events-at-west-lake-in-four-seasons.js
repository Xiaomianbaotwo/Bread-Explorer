茅家埠之夏，芦苇青绿，水道曲折，野趣自生。芦叶修长，层层向上，风过时，绿浪起伏，声如细雨。木栈道静卧水畔，板上苔痕微润，两侧芦苇掩映，水光漏成碎点。水鸟低飞，翅影掠过芦尖，落入深处；蜻蜓停在荷角，翅薄透明，忽而飞去。湖面窄处，水草丰茂，浮萍聚散，蛙鸣自草丛中传出，与远处蝉声相应。此处不似外湖开阔，却多幽静；不似苏堤明丽，却多野逸。夏花在岸边自开自落，紫薇一枝，红得明亮；合欢如绒，粉得轻柔；栀子若白，香在叶底。花影入水，水亦生香。

夏夜西湖，月与荷相映。月出东山，清光落湖，湖面如铺素练。三潭印月，塔影静立，月光在水，水在月下，波光与月影相涵。荷塘深处，花影朦胧，叶影沉黑，偶有鱼跃，碎光四散。风从湖面来，带着水汽与荷香，穿过柳梢，掠过桥栏，归于远山。此时无声，唯有水光、月光、花影、叶影，彼此交错，清冷而丰盈。夏之西湖，因荷而盛，因雨而新，因月而静，因风而远。

秋桂

秋之西湖，桂香先至。满觉陇一带，山径曲折，桂树成林，金粟满枝，细碎如星。风过处，花粒轻落，铺于石上，铺于苔间，铺于草根；香气不袭，而自浮，自远，自清。晨露未干，桂香带湿；午后日暖，桂香更甜；暮色降时，香气沉入山影，随夜气漫入湖湾。桂有金桂、银桂、丹桂，色分深浅，香有浓淡，皆不与百花争春，只在秋清之中，自成一段幽馥。

湖上秋光，与桂香同至。天高云薄，水色更清，山影更瘦。苏堤柳叶渐黄，桃叶转褐，长堤不再如春时明艳，却多一层沉静。六桥栏上，苔痕带露，桥孔映水，圆影如月。湖面开阔，风来波纹细长，日光落处，碎金满波；云影过处，水面忽明忽暗。远山轮廓清晰，南屏、夕照、宝石、葛岭，皆在清秋里显出筋骨。秋阳不烈，照在湖上，照在叶上，照在残荷上，皆带温和的旧色。

曲院秋深，荷塘已改。盛夏时的碧叶红花，渐成残梗枯叶。荷叶卷边，色如古铜；荷梗折断，斜插水面；莲蓬低垂，籽实已老。雨落残荷，声清而冷，点滴之间，别有一种秋意。风过处，枯叶轻摇，水纹微动，花影虽无，骨格犹存。残荷不显衰败，反见清寂；水面因之更空，天光因之更明。几只水鸟停于浅处，羽色映波，忽然飞起，掠过残梗，没于芦岸。秋荷之美，不在盛放，而在静守；不在颜色，而在声影。

茅家埠之秋，芦花渐白。初时芦穗青中带紫，继而转白，终于如雪。风来，芦花轻摇，白浪起伏；风定，芦影静立，水边一片素色。木栈道临水，板上落叶零星，水光在板缝间闪动。芦苇深处，水鸟低鸣，翅影起落，时而隐入深处，时而浮出浅湾。湖湾曲折，水道纵横，芦花映水，水色亦白。秋阳斜照，芦穗边缘透出金光；暮色四合，芦影渐淡，唯余风声与水声。此处秋意，不在高处，而在低处；不在明艳，而在苍茫。

孤山秋深，菊影清瘦。菊花依石而开，瓣有卷舒，色有白黄紫红。白者如霜，黄者如金，紫者如暮云，红者如晚霞。花瓣细长，叶色深绿，枝干挺立，带一点清冷之气。菊影落在石上，落在墙根，落在湖畔，风来微动，似有幽香。桂花在山间，菊花在石畔，芦花在湖湾，秋花各居其所，共同织成西湖秋色。秋叶亦添层次：梧桐黄，乌桕红，枫叶赤，樟叶仍绿，杂树相间，山色由青转苍，由苍转深。叶落水面，随波轻旋，漂向桥孔，漂向湖心，漂向远处。

秋晨露重，草叶垂珠，桂枝凝香。湖面轻雾未散，山影淡，水色冷。露落残荷，声极轻；露坠桂叶，香微动。石阶苔痕带湿，桥栏水珠映光。秋露不似春雨细密，却使湖山更清。秋夜虫声起于岸草，低而清。桂影下，菊丛边，芦岸深处，虫鸣断续，与蛙声渐稀。虫声不闹，衬出湖夜之静；月色因之更明，水光因之更冷。

秋月最宜湖上。平湖一带，水面开阔，月出时，清光铺满湖面，波纹不动，湖如素练。月影在水中，山影在月下，天光水光相接，清冷无际。桂香随风暗度，菊影在石边静立，芦花在远处摇白。秋夜无声，唯有露气渐重，叶声偶响，水鸟栖定，湖山俱寂。秋之西湖，因桂而香，因菊而清，因芦而远，因月而空。盛景之后，归于澄明；繁华褪尽，更见本色。

冬梅

冬之西湖，先寒于水。湖面清瘦，山色苍茫，天光低垂，云影缓慢。柳叶尽落，枝条疏朗，苏堤不再浓绿，只剩长条在风中轻摆。桃枝空瘦，桥栏带霜，六桥静卧于寒波之上，轮廓清峻。水色比春夏更深，更冷，更静；风过处，波纹细密，如皱起的素绢。远山淡淡，近石苍苍，湖上空气清冽，若含冰雪。冬花不多，却因少而更显；冬景不繁，却因静而更深。

孤山冬梅，为西湖冬花之魂。梅枝瘦硬，老干如铁，花未放时，枝影横斜，已有清意；花初放时，点点白瓣，缀于寒枝，如雪未消；花盛时，冷香浮动，香不浓烈，却入水入石，入暮色，入晨霜。白梅映水，水亦清寒；红梅倚石，石亦生暖。雪落孤山，梅与雪相映，枝上花与空中雪同白，湖上雾与山间云同淡。雪后石阶洁净，梅影落雪，疏淡如画；雪压枝头，花仍微开，冷香更清。西泠桥畔，水波不兴，梅影沉于湖底，桥影横于波心，天地之间，唯余清白。

断桥冬雪，为湖上清绝。雪落白堤，长堤一线皆白；桥面积雪未融，桥影似断。湖面雾气轻浮，山影隐现，树色苍茫，亭台楼阁皆披素色。雪中之湖，繁声俱寂，唯有雪落枝头的微响，风过湖面的轻响，冰痕初结的细响。残荷覆雪，枯梗低垂，叶上积雪如银；芦苇压雪，白穗与雪同色，风来轻颤，雪粒纷落。冬鸟栖于浅水，羽色映雪，忽然飞起，掠过湖面，翅影划破寒光。雪后初晴，日光落在湖上，雪色映天，湖面明亮，山影清瘦，西湖如一幅淡墨长卷。

冬晨湖上有雾，轻白如纱，浮于水面，绕于桥孔，缠于柳梢。雾中苏堤只余一线，远山隐没，塔影淡成墨痕。雾散时，湖面渐明，梅枝渐显，水鸟翅影忽然掠过，寒光一闪。冬日初晴，湖冰薄处映光，石霜化水，梅瓣沾露。天蓝而冷，山瘦而清，枝影落湖，如细笔勾勒。阳光不暖，却使雪色更白，梅色更明。湖上空气冷冽，花影清峻，冬之骨格尽现。

冬山茶与蜡梅，点缀湖山。山茶叶绿而厚，花红而润，在寒风中开出暖意；蜡梅枝瘦，花黄如蜡，香清而冷，生于石畔墙根。山茶映雪，红白相照；蜡梅临水，黄影浮波。冬花不借春色，不倚夏雨，不待秋风，只在寒中自成一段清骨。湖上冬树，枝干交错，线条清峻；山石瘦硬，苔痕半枯，雪落之后，石骨更显。保俶塔立于宝石山巅，雪影衬天，清瘦而静；雷峰塔在夕照山侧，暮色中塔影沉黑，湖光冷白。塔影与雪光相映，冬之西湖更见空阔。

